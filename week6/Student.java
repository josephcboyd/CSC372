public class Student {
    int rollno;
    String name;
    String address;
    

    public int getRollno() {
        return this.rollno;
    }

    public void setRollno(int value) {
        this.rollno = value;
    }

    public String getName() {
        return this.name;
    }

    public void setName(String value) {
        this.name = value;
    }

    public String getAddress() {
        return this.address;
    }

    public void setAddress(String value) {
        this.address = value;
    }


}